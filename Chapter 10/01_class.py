class Employee:
    language = "Python" # This is a class attribute
    salary = 1000000

Prannay = Employee()
Prannay.name = "Prannay" # This is an instance attribute
print(Prannay.salary, Prannay.language, Prannay.name.upper(), Prannay.name.title())
# Here name is instance attribute and salary and language are class attributes as they directly belong to the class



